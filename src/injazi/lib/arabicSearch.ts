/*
  بحث عربي يتسامح مع اختلاف الكتابة.
  ------------------------------------------------------------------
  «نادين الشمرانى» و«نادين الشمراني» اسم واحد، لكن المقارنة الحرفية
  تراهما مختلفين، فيعود البحث فارغًا ويظنّ من يبحث أن البيانات ضائعة.
  وهذا ليس خطأ نادرًا: لوحات المفاتيح على الجوّالات تكتب «ى» حيث تكتب
  غيرها «ي»، والأسماء تُكتب بهمزة حينًا وبلا همزة حينًا.

  فنُوحِّد الشكل قبل المقارنة:
    • الهمزات كلها (أ إ آ ٱ) → ا
    • ى → ي   ،   ة → ه   ،   ؤ → و   ،   ئ → ي
    • تُحذف الحركات والتطويل (ـ)
    • تُحوَّل الأرقام العربية-الهندية (٠١٢…) إلى لاتينية
    • تُطوى المسافات المتكرّرة، ويُصغَّر الحرف اللاتيني

  ما لا نفعله: لا نحذف «ال» التعريف ولا نطابق تقريبيًا، فالبحث يجب أن
  يبقى متوقَّعًا — التساهل في الشكل لا في المعنى.
*/

/** المحارف التي تُحذف: الحركات والتنوين والشدّة والسكون والتطويل. */
const STRIPPED = /[ً-ْٰـ]/g;

const FOLD: Record<string, string> = {
  "أ": "ا", // أ
  "إ": "ا", // إ
  "آ": "ا", // آ
  "ٱ": "ا", // ٱ
  "ى": "ي", // ى → ي
  "ة": "ه", // ة → ه
  "ؤ": "و", // ؤ → و
  "ئ": "ي", // ئ → ي
};

/** ٠١٢٣٤٥٦٧٨٩ (عربية-هندية) و۰۱۲… (فارسية) إلى 0-9. */
function latinDigits(text: string): string {
  return text.replace(/[٠-٩۰-۹]/g, (digit) =>
    String(((digit.codePointAt(0) ?? 0) - 0x0660) % 10),
  );
}

/** الشكل الموحَّد للنص، للمقارنة وحدها — لا يُعرَض للمستخدمة أبدًا. */
export function normalizeArabic(text: string): string {
  return latinDigits(text)
    .replace(STRIPPED, "")
    .replace(/[أإآٱىةؤئ]/g, (char) => FOLD[char] ?? char)
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/**
 * هل يحتوي النص على ما يُبحث عنه، بصرف النظر عن شكل الكتابة؟
 * إبرة فارغة تُطابق كل شيء — أي «لا تصفية».
 */
export function textMatches(haystack: string, needle: string): boolean {
  const target = normalizeArabic(needle);
  if (!target) return true;
  return normalizeArabic(haystack).includes(target);
}
