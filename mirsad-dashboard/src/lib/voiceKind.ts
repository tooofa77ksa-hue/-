/**
 * فرز آراء الطالبات: ما يُطلب فيه عمل، وما هو شكر، وما لا مضمون فيه.
 *
 * الإدارة تحتاج «ما الذي يُصلَح» وحده. وكان عليها أن تمرّ على مئة رأي
 * أكثرها «لا يوجد» و«شكرًا لكم» لتصل إلى ما يُعمَل به. فهذا الفرز
 * يضع كل رأي في بابه، ولا يحذف شيئًا: الشكر يُعرض في بابه، وما لا
 * مضمون فيه يُطوى ويبقى في عدّه.
 *
 * والفرز بالكلمات يخطئ حتمًا — رأيٌ يطلب أنشطةً بعبارة لطيفة قد
 * يُقرأ ثناءً. فقرار الإدارة يغلب عليه دائمًا (الحقل «kind» في
 * الرأي)، ولذلك وُضع زرّ النقل بين الأبواب في الشاشة.
 */
