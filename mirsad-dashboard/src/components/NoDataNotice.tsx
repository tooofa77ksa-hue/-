import { useSystem } from '../state/useSystem'

/**
 * تنبيه غياب البيانات.
 *
 * يُعرض حين تكون الحالة فارغة فعلًا، لا حين تكون البيانات مستثناة من
 * ملفات المتصفّح — ففي الوضع المنشور تُقرأ البيانات من قاعدة البيانات
 * لا من الحزمة، وإظهار التنبيه حينها كذبٌ على الإدارة.
 */
export function NoDataNotice() {
  const { mode } = useSystem()

  return (
    <div className="alert alert--info">
      {mode === 'remote' ? (
        <span>
          <strong>لا توجد بيانات في قاعدة البيانات بعد.</strong> ارفعيها من
          «الإعدادات ← قاعدة البيانات»، أو استعيدي نسخة احتياطية.
        </span>
      ) : (
        <span>
          <strong>لم تُحمَّل بيانات المدرسة.</strong> ملفات الطالبات والاستجابات مستثناة من
          المستودع لأنها بيانات شخصية. ضعي ملفات المصدر في <code>data/source/</code> ثم
          شغّلي <code>npm run etl</code> لتوليدها محليًا.
        </span>
      )}
    </div>
  )
}
